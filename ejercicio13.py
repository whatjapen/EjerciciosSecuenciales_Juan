n = float(input("Número: "))
print("Cuadrada:", n ** 0.5)       # elevar a 1/2
print("Cúbica:", n ** (1 / 3))     # elevar a 1/3

#¿Cómo se puede calcular?
#Es tan sencillo como elevar a 1/3 para raiz cúbica o elevar a 1/2 para raiz cuadrada.